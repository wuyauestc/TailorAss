#!/usr/bin/env python3
"""Check dynamic torso placement formulas against pinned official JSON.

No upstream checkout or Python clothing dependencies are required. The input
fixtures were generated by GenerateOfficialGoldens.py, which enforces commit
d449629979028123a5c4dc9e732a2ec19b7fce31. This checks initial placement, not a
physical drape or the native App's solver. Source JSON is never changed.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--repo-dir',type=Path,default=Path(__file__).resolve().parents[2])
parser.add_argument('--output-dir',type=Path,default=Path('/private/tmp/TailorAssTorsoPlacement'))
args=parser.parse_args()
ROOT=args.repo_dir.resolve()
OUT=args.output_dir.resolve()
OUT.mkdir(parents=True,exist_ok=True)
catalog=json.loads((ROOT/'TrailorAss/Resources/GarmentCodeParameterCatalog.json').read_text())
COMMIT='d449629979028123a5c4dc9e732a2ec19b7fce31'
assert catalog['source']['commit']==COMMIT,'Parameter catalogue source commit differs'
fixture_hashes={}
def fixture(name):
    path=ROOT/'Tests/NativePattern/Fixtures'/f'{name}.json'
    data=path.read_bytes()
    fixture_hashes[path.name]=hashlib.sha256(data).hexdigest()
    return json.loads(data)
def formulas(body,fitted,width=1.05,length=1.2):
    H=body['height']-body['head_l'];t=math.tan(math.radians(body.get('_shoulder_incl',body['shoulder_incl'])))
    F=(body['bust']-body['back_width'])/2;B=body['back_width']/2;S=body['shoulder_w']/2
    if fitted:
        Lf=body['waist_over_bust_line']-t*(F-S);Lb=body['waist_line']-t*(B-S)
        p0=t*B/4
        return dict(front=[0,H-Lf-t*F,30],back=[0,H-Lb-t*B+p0,-25],preSerializationBackPivotY=p0,alreadySubtractedBackIntegerPivotY=math.trunc(p0))
    Lb=length*body['waist_line'];Lf=Lb-t*(F-B)
    return dict(front=[0,H-Lf-t*width*F,30],back=[0,H-Lb-t*width*B,-25],preSerializationBackPivotY=0,alreadySubtractedBackIntegerPivotY=0)
checks=[]
def check(doc,body,style,case,width=1.05,length=1.2,asym=False):
    for name,panel in doc['pattern']['panels'].items():
        if not (name.endswith('_ftorso') or name.endswith('_btorso')):continue
        w=1.0 if asym and name.startswith('left_') else width
        f=formulas(body,style=='FittedShirt',w,length)
        expected=f['front' if name.endswith('_ftorso') else 'back']
        err=max(abs(a-b) for a,b in zip(panel['translation'],expected))
        r=max(abs(v) for v in panel['rotation'])
        assert err<1e-9 and r<1e-9,(case,name,expected,panel['translation'],err)
        checks.append(dict(case=case,panel=name,translationCM=expected,maxErrorCM=err,rotationDegrees=panel['rotation'],preSerializationBackPivotY=f['preSerializationBackPivotY'],alreadySubtractedBackIntegerPivotY=f['alreadySubtractedBackIntegerPivotY']))
base=catalog['body']
for file,style,kw in [
 ('shirt','Shirt',{}),('shirt-varied','Shirt',dict(width=1.2,length=1.5)),
 ('shirt-asymmetric','Shirt',dict(asym=True)),('fitted-shirt','FittedShirt',{}),
 ('fitted-shirt-asymmetric','FittedShirt',dict(asym=True)),('fitted-shirt-strapless','FittedShirt',{}),
 ('shirt-sleeved','Shirt',{}),('fitted-shirt-sleeved','FittedShirt',{}),
 ('shirt-collar-SimpleLapel','Shirt',{}),('fitted-shirt-collar-SimpleLapel','FittedShirt',{}),
 ('shirt-collar-Hood2Panels','Shirt',{}),('fitted-shirt-collar-Hood2Panels','FittedShirt',{})]:
    check(fixture(file),base,style,file,**kw)
for file in ['meta-grid-defaults','meta-grid-female']:
    raw=fixture(file);patterns=raw.get('patterns',raw);body=raw.get('body',base)
    for name,doc in patterns.items():
        style=name.split('|')[0]
        if style in ['Shirt','FittedShirt']:check(doc,body,style,file+':'+name)
assert len(checks)==480,'Expected complete two-body meta torso matrix and explicit torso variants'
report=dict(passed=True,checkedPanels=len(checks),maximumTranslationErrorCM=max(x['maxErrorCM'] for x in checks),checks=checks,
           upstreamCommit=COMMIT,fixtureSHA256=fixture_hashes,
           fixtureGeneratorSHA256=hashlib.sha256((ROOT/'Tests/NativePattern/GenerateOfficialGoldens.py').read_bytes()).hexdigest(),
           formulaConventions='centimetres, source serialized XY already includes integer pivot subtraction; rotations all zero, left is already mirrored in source XY',
           fittedBackPivotWarning='Add full t*B/4 to the original Tbase for the serialized transform. Do not add only trunc(t*B/4), do not subtract that integer from serialized mesh again. The full-vs-integer difference preserves the pinned upstream assembly convention.')
(OUT/'torso-formula-proof.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print('PASS',len(checks),'official torso panels; max translation delta cm',report['maximumTranslationErrorCM'])
